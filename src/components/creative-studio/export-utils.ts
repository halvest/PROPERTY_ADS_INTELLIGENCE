function loadImage(src: string): Promise<HTMLImageElement> {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.crossOrigin = "anonymous";
    img.onload = () => resolve(img);
    img.onerror = (e) => reject(e);
    img.src = src;
  });
}

function roundRect(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  width: number,
  height: number,
  radius: number
) {
  ctx.beginPath();
  ctx.moveTo(x + radius, y);
  ctx.lineTo(x + width - radius, y);
  ctx.quadraticCurveTo(x + width, y, x + width, y + radius);
  ctx.lineTo(x + width, y + height - radius);
  ctx.quadraticCurveTo(x + width, y + height, x + width - radius, y + height);
  ctx.lineTo(x + radius, y + height);
  ctx.quadraticCurveTo(x, y + height, x, y + height - radius);
  ctx.lineTo(x, y + radius);
  ctx.quadraticCurveTo(x, y, x + radius, y);
  ctx.closePath();
}

/**
 * Direct High-Fidelity Raster Image Downloader for Meta Muse Image 1.0 Studio
 * Renders the pure generated image onto an offscreen HTML5 canvas at target dimensions
 * with high-quality bicubic smoothing and triggers a direct browser download.
 */
export async function downloadStudioImage(
  imageUrl: string,
  format: "png" | "jpeg" | "webp" = "png",
  aspectRatio: string = "auto",
  fileName?: string
): Promise<void> {
  const img = await loadImage(imageUrl);
  const naturalW = img.naturalWidth || img.width || 1080;
  const naturalH = img.naturalHeight || img.height || 1080;

  let targetW = naturalW;
  let targetH = naturalH;

  switch (aspectRatio) {
    case "1:1":
      targetW = 1080;
      targetH = 1080;
      break;
    case "4:5":
      targetW = 1080;
      targetH = 1350;
      break;
    case "2:3":
      targetW = 1024;
      targetH = 1536;
      break;
    case "9:16":
      targetW = 1080;
      targetH = 1920;
      break;
    case "16:9":
      targetW = 1920;
      targetH = 1080;
      break;
    case "auto":
    default:
      targetW = naturalW;
      targetH = naturalH;
      break;
  }

  const canvas = document.createElement("canvas");
  canvas.width = targetW;
  canvas.height = targetH;
  const ctx = canvas.getContext("2d");
  if (!ctx) return;

  ctx.imageSmoothingEnabled = true;
  ctx.imageSmoothingQuality = "high";

  // Fit image into target canvas with high quality cover / containment
  const srcRatio = naturalW / naturalH;
  const targetRatio = targetW / targetH;

  let drawW = targetW;
  let drawH = targetH;
  let drawX = 0;
  let drawY = 0;

  if (Math.abs(srcRatio - targetRatio) < 0.05) {
    drawW = targetW;
    drawH = targetH;
  } else if (srcRatio > targetRatio) {
    // Source is wider than target: cover vertically, center horizontally
    drawH = targetH;
    drawW = Math.round(targetH * srcRatio);
    drawX = Math.round((targetW - drawW) / 2);
  } else {
    // Source is taller than target: cover horizontally, center vertically
    drawW = targetW;
    drawH = Math.round(targetW / srcRatio);
    drawY = Math.round((targetH - drawH) / 2);
  }

  ctx.drawImage(img, drawX, drawY, drawW, drawH);

  const mimeType =
    format === "png"
      ? "image/png"
      : format === "webp"
      ? "image/webp"
      : "image/jpeg";
  const quality = format === "png" ? undefined : 0.95;
  const dataUrl = canvas.toDataURL(mimeType, quality);

  const safeFileName =
    fileName ||
    `property-ad-${aspectRatio.replace(":", "x")}-${Date.now()}.${
      format === "jpeg" ? "jpg" : format
    }`;

  const link = document.createElement("a");
  link.href = dataUrl;
  link.download = safeFileName;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}
