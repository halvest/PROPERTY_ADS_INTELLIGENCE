/**
 * Samples the top 8% sky strip (left, center, right) and bottom 8% ground strip of the property photo.
 */
function samplePhotoSkyAndGround(
  img: HTMLImageElement,
  sw: number,
  sh: number
): SampledSkyPalette {
  const fallback: SampledSkyPalette = {
    left: [186, 202, 214],
    center: [196, 212, 224],
    right: [182, 198, 212],
    zenith: [168, 190, 208],
    bottomGround: [242, 240, 235],
  };

  try {
    const probeW = 48;
    const probeH = 48;
    const probe = document.createElement("canvas");
    probe.width = probeW;
    probe.height = probeH;
    const pCtx = probe.getContext("2d");
    if (!pCtx) return fallback;

    pCtx.drawImage(img, 0, 0, sw, sh, 0, 0, probeW, probeH);
    const data = pCtx.getImageData(0, 0, probeW, probeH).data;

    const avgRegion = (x0: number, x1: number, y0: number, y1: number): [number, number, number] => {
      let r = 0;
      let g = 0;
      let b = 0;
      let count = 0;
      for (let y = y0; y < y1; y++) {
        for (let x = x0; x < x1; x++) {
          const idx = (y * probeW + x) * 4;
          r += data[idx];
          g += data[idx + 1];
          b += data[idx + 2];
          count++;
        }
      }
      if (count === 0) return [196, 212, 224];
      return [Math.round(r / count), Math.round(g / count), Math.round(b / count)];
    };

    const left = avgRegion(0, 16, 0, 5);
    const center = avgRegion(16, 32, 0, 5);
    const right = avgRegion(32, 48, 0, 5);
    const zenith: [number, number, number] = [
      Math.max(24, Math.round(center[0] * 0.92)),
      Math.max(28, Math.round(center[1] * 0.94)),
      Math.max(36, Math.round(center[2] * 0.97)),
    ];
    const bottomGround = avgRegion(4, 44, 42, 48);

    return { left, center, right, zenith, bottomGround };
  } catch {
    return fallback;
  }
}

function hexToRgb(hex: string): [number, number, number] | null {
  const clean = hex.replace("#", "").trim();
  if (clean.length !== 6) return null;
  const num = parseInt(clean, 16);
  if (Number.isNaN(num)) return null;
  return [(num >> 16) & 255, (num >> 8) & 255, num & 255];
}

function rgbToCss(rgb: [number, number, number], alpha: number): string {
  return `rgba(${rgb[0]}, ${rgb[1]}, ${rgb[2]}, ${alpha})`;
}

/**
 * Adapts a pure generated AI flyer image across 1:1, 4:5, and 9:16 without stretching.
 */
function drawPureGeneratedFlyerAdapted(
  ctx: CanvasRenderingContext2D,
  pureImg: HTMLImageElement,
  width: number,
  height: number,
  aspectRatio: AspectRatio
) {
  const sw = pureImg.naturalWidth || pureImg.width || width;
  const sh = pureImg.naturalHeight || pureImg.height || height;
  const srcRatio = sw / sh;
  const dstRatio = width / height;

  if (Math.abs(srcRatio - dstRatio) < 0.04) {
    ctx.drawImage(pureImg, 0, 0, width, height);
    return;
  }

  // Draw smooth blurred ambient background to eliminate harsh borders
  ctx.save();
  ctx.filter = "blur(28px) saturate(1.12) brightness(0.96)";
  ctx.drawImage(pureImg, -24, -24, width + 48, height + 48);
  ctx.restore();

  // Subtle dark vignette to elevate foreground contrast
  ctx.fillStyle = "rgba(0, 0, 0, 0.12)";
  ctx.fillRect(0, 0, width, height);

  // Contain scaling: preserve 100% of flyer content with zero clipping
  const scale = Math.min(width / sw, height / sh);
  const drawW = Math.round(sw * scale);
  const drawH = Math.round(sh * scale);
  const drawX = Math.round((width - drawW) / 2);
  const drawY = Math.round((height - drawH) / 2);

  ctx.save();
  ctx.shadowColor = "rgba(0, 0, 0, 0.32)";
  ctx.shadowBlur = 28;
  ctx.shadowOffsetY = 6;
  ctx.drawImage(pureImg, drawX, drawY, drawW, drawH);
  ctx.restore();
}

/**
 * Draws the Developer Logo badge at high resolution with automatic light/dark contrast detection.
 */
function bakeSmartDeveloperLogo(
  ctx: CanvasRenderingContext2D,
  logoImg: HTMLImageElement,
  width: number,
  height: number,
  margin: number,
  aspectRatio: AspectRatio,
  logoPlacement?: "top-left" | "top-right" | "auto"
): { x: number; y: number; width: number; height: number; placedLeft: boolean } {
  const rawW = logoImg.naturalWidth || logoImg.width || 200;
  const rawH = logoImg.naturalHeight || logoImg.height || 80;
  const aspect = rawW / Math.max(1, rawH);

  const maxLogoH = 42;
  const minLogoH = 28;
  const maxLogoW = 150;

  let logoH = Math.min(Math.max(rawH, minLogoH), maxLogoH);
  let logoW = logoH * aspect;

  if (logoW > maxLogoW) {
    logoW = maxLogoW;
    logoH = logoW / aspect;
  }

  let isLightLogo = false;
  let hasOpaqueBg = false;
  try {
    const probe = document.createElement("canvas");
    probe.width = 32;
    probe.height = 32;
    const pCtx = probe.getContext("2d");
    if (pCtx) {
      pCtx.drawImage(logoImg, 0, 0, 32, 32);
      const data = pCtx.getImageData(0, 0, 32, 32).data;
      let lumSum = 0;
      let visCount = 0;
      for (let i = 0; i < data.length; i += 4) {
        const a = data[i + 3];
        if (a > 40) {
          lumSum += 0.299 * data[i] + 0.587 * data[i + 1] + 0.114 * data[i + 2];
          visCount++;
        }
      }
      const avgLum = visCount > 0 ? lumSum / visCount : 128;
      const cornerIndices = [0, 31 * 4, 31 * 32 * 4, (32 * 32 - 1) * 4];
      const opaqueCorners = cornerIndices.filter((idx) => data[idx + 3] > 235).length;
      hasOpaqueBg = opaqueCorners >= 3;
      isLightLogo = !hasOpaqueBg && avgLum > 195;
    }
  } catch {
    // Default to light card if pixel probing fails
  }

  const padX = hasOpaqueBg ? 8 : 16;
  const padY = hasOpaqueBg ? 8 : 10;
  const pillW = Math.round(logoW + padX * 2);
  const pillH = Math.round(logoH + padY * 2);

  const bounds = getSafeZoneBounds(width, height, aspectRatio);
  const placedLeft = logoPlacement === "top-left";
  const pillX = placedLeft ? bounds.safeRect.x : bounds.safeRect.rightX - pillW;
  const pillY = bounds.safeRect.y;

  ctx.save();
  ctx.shadowColor = "rgba(0, 0, 0, 0.22)";
  ctx.shadowBlur = 14;
  ctx.shadowOffsetY = 4;

  if (isLightLogo) {
    ctx.fillStyle = "rgba(20, 24, 31, 0.88)";
    roundRect(ctx, pillX, pillY, pillW, pillH, 14);
    ctx.fill();
    ctx.shadowBlur = 0;
    ctx.strokeStyle = "rgba(231, 216, 197, 0.35)";
    ctx.lineWidth = 1.2;
    ctx.stroke();
  } else {
    ctx.fillStyle = "rgba(255, 255, 255, 0.94)";
    roundRect(ctx, pillX, pillY, pillW, pillH, 14);
    ctx.fill();
    ctx.shadowBlur = 0;
    ctx.strokeStyle = "rgba(15, 23, 42, 0.12)";
    ctx.lineWidth = 1.2;
    ctx.stroke();
  }
  ctx.restore();

  ctx.drawImage(
    logoImg,
    Math.round(pillX + padX),
    Math.round(pillY + padY),
    Math.round(logoW),
    Math.round(logoH)
  );

  return { x: pillX, y: pillY, width: pillW, height: pillH, placedLeft };
}

function truncateTextToWidth(
  ctx: CanvasRenderingContext2D,
  text: string,
  maxWidth: number
): string {
  if (ctx.measureText(text).width <= maxWidth) return text;
  let truncated = text;
  while (truncated.length > 4 && ctx.measureText(`${truncated}…`).width > maxWidth) {
    truncated = truncated.slice(0, -1);
  }
  return `${truncated}…`;
}

function wrapTextLines(
  ctx: CanvasRenderingContext2D,
  text: string,
  maxWidth: number,
  maxLines: number = 2
): string[] {
  const words = text.split(/\s+/).filter(Boolean);
  if (words.length === 0) return [];
  const lines: string[] = [];
  let currentLine = "";

  for (let i = 0; i < words.length; i++) {
    const word = words[i];
    const testLine = currentLine ? `${currentLine} ${word}` : word;
    const testW = ctx.measureText(testLine).width;

    if (testW > maxWidth && currentLine) {
      lines.push(currentLine);
      currentLine = word;
      if (lines.length === maxLines - 1) {
        // Collect all remaining words into the final line
        const remaining = words.slice(i + 1).join(" ");
        if (remaining) {
          currentLine = `${currentLine} ${remaining}`;
        }
        break;
      }
    } else {
      currentLine = testLine;
    }
  }

  if (currentLine && lines.length < maxLines) {
    lines.push(truncateTextToWidth(ctx, currentLine, maxWidth));
  }

  return lines;
}

/**
 * Advanced Typography Engine:
 * Dynamically scales font size to ensure multi-line headlines and project titles fit
 * into the allocated bounding box without clipping, truncation, or awkward ellipses.
 */
function calculateOptimalFontSize(
  ctx: CanvasRenderingContext2D,
  text: string,
  maxWidth: number,
  maxLines: number,
  fontFamily: string,
  fontWeight: string | number,
  preferredSize: number = 38,
  minSize: number = 18
): { fontSize: number; lines: string[] } {
  // 1. Try finding a font size where all lines fit without any truncation ellipsis
  for (let size = preferredSize; size >= minSize; size -= 2) {
    ctx.font = `${fontWeight} ${size}px ${fontFamily}`;
    const lines = wrapTextLines(ctx, text, maxWidth, maxLines);
    if (lines.length <= maxLines) {
      const allFit = lines.every((line) => !line.endsWith("…") && !line.endsWith("...") && !line.includes("…"));
      if (allFit) {
        return { fontSize: size, lines };
      }
    }
  }

  // 2. If still overflowing, scale down further to prevent ellipsis on key project names
  for (let size = minSize - 2; size >= 14; size -= 2) {
    ctx.font = `${fontWeight} ${size}px ${fontFamily}`;
    const lines = wrapTextLines(ctx, text, maxWidth, maxLines);
    if (lines.length <= maxLines) {
      const allFit = lines.every((line) => !line.endsWith("…") && !line.endsWith("...") && !line.includes("…"));
      if (allFit) {
        return { fontSize: size, lines };
      }
    }
  }

  // 3. Fallback at minimum size (clean wrap)
  ctx.font = `${fontWeight} 14px ${fontFamily}`;
  return { fontSize: 14, lines: wrapTextLines(ctx, text, maxWidth, maxLines) };
}

